# Функция для анализа логов через API VirusTotal
def analyze_with_virustotal(ip_address):
    headers = {'x-apikey': VT_API_KEY}
    response = requests.get(f'https://www.virustotal.com/api/v3/ip_addresses/{ip_address}', headers=headers)
    if response.status_code == 200:
        return response.json()
    else:
        return None

# Функция для анализа подозрительности IP из файла random_ips.txt
def analyze_random_ips(file_path='random_ips.txt'):
    with open(file_path, 'r') as file:
        ips = file.read().splitlines()
    results = []
    for ip in ips:
        analysis_result = analyze_with_virustotal(ip)
        if analysis_result:
            threat_level = analysis_result['data']['attributes']['last_analysis_stats']['malicious']
