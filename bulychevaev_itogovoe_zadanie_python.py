# Генерация случайных значений из закрытых списков для IP, протокола, нагрузки, ID правил, уровня серьезности, отметки угрозы, категории угрозы
def random_ip():
    return '.'.join(map(str, (random.randint(0, 255) for _ in range(4))))

def random_protocol():
    protocols = ['TCP', 'UDP', 'HTTP', 'FTP', 'SSH', 'DNS']
    return random.choice(protocols)

def random_payload(size=10):
    letters = string.ascii_letters + string.digits
    return ''.join(random.choice(letters) for i in range(size))

def random_rule_id():
    return random.randint(1000, 9999)

def random_severity():
    severities = ['INFO', 'LOW', 'MEDIUM', 'HIGH', 'CRITICAL']
    return random.choice(severities)

def random_signature():
    signatures = [
        'Possible SQL injection attempt',
        'Potential XSS attack detected',
        'Malformed packet detected',
        'Suspicious port scan activity',
        'DDoS traffic detected',
        'Unauthorised access attempt',
        'Malware infection detected',
        'Data exfiltration attempt'
    ]
    return random.choice(signatures)

def random_category():
    categories = ['Attack', 'Network Activity', 'Anomaly', 'Malware', 'Policy Violation']
    return random.choice(categories)

# Генерируем 100 логов
def generate_suricata_logs(num_entries=100):
    start_time = datetime.now(timezone.utc) - timedelta(hours=1)
    logs = []

    for _ in range(num_entries):
        timestamp = start_time.strftime('%Y-%m-%dT%H:%M:%SZ')
        event_type = random.choice(['alert', 'drop'])
        source_ip = random_ip()
        destination_ip = random_ip()
        protocol = random_protocol()
        payload = random_payload()
        rule_id = random_rule_id()
        severity = random_severity()
        signature = random_signature()
        category = random_category()
        destination_port = random.randint(1024, 65535)

        log_entry = {
            "timestamp": timestamp,
            "event_type": event_type,
            "source_ip": source_ip,
            "destination_ip": destination_ip,
            "protocol": protocol,
            "payload": payload,
            "rule_id": rule_id,
            "severity": severity,
            "signature": signature,
            "category": category,
            "destination_port": destination_port
        }

        logs.append(log_entry)
        start_time += timedelta(seconds=random.randint(1, 10))

    return logs

# Записываем логи в файл suricata.log (он сгенерирован и приложен к ДЗ)
def save_logs_to_file(logs, filename='suricata.log'):
    with open(filename, 'w') as file:
        for log in logs:
            file.write(json.dumps(log) + "\n")

